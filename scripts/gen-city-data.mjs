// usage: node scripts/gen-city-data.mjs <checkedOn YYYY-MM-DD> <dir-with-<slug>.json files>
import fs from "node:fs";
import path from "node:path";
const [checkedOn, dir] = process.argv.slice(2);
const CORE = ["lead-generation", "seo", "website-development", "branding"];
const FIELDS = ["population2021", "population2016", "growthPct", "medianAge", "medianHouseholdIncome2020", "privateDwellings", "landAreaKm2"];
const clean = (s) => String(s ?? "").replace(/\s+/g, " ").replace(/—/g, ", ").replace(/–/g, " to ").replace(/ , /g, ", ").trim();
const isUrl = (u) => /^https?:\/\/[^\s"'<>]+$/.test(u || "");
const numbersIn = (s) => (s.match(/\d[\d,]*(?:\.\d+)?/g) || []).map((n) => n.replace(/,/g, ""));
const allowedNumbers = (figures, facts) => {
  const set = new Set(["2016", "2020", "2021"]);
  const add = (n) => {
    if (n == null) return;
    const num = Number(String(n).replace(/,/g, ""));
    if (!Number.isFinite(num)) return;
    for (const v of [String(n), String(num), String(Math.round(num)), num.toFixed(1), num.toFixed(2)]) set.add(v.replace(/\.0+$/, ""));
    if (num >= 1e6) for (const v of [(num / 1e6).toFixed(1), (num / 1e6).toFixed(2)]) set.add(v.replace(/\.0+$/, ""));
    if (num >= 1e3) for (const v of [(num / 1e3).toFixed(0), (num / 1e3).toFixed(1)]) set.add(v.replace(/\.0+$/, ""));
    // "roughly 750,000" style rounding of populations
    if (num >= 1e4) { set.add(String(Math.round(num / 1000) * 1000)); set.add(String(Math.round(num / 10000) * 10000)); }
  };
  Object.values(figures).forEach(add);
  for (const f of facts) numbersIn(f.text).forEach(add);
  return set;
};
const scrub = (text, allowed) => text.split(/(?<=[.!?])\s+/).filter((s) => !numbersIn(s).some((n) => !allowed.has(n.replace(/\.0+$/, "")))).join(" ");

const out = {};
let figures = 0, facts = 0, withCopy = 0, scrubbed = 0;
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  let c;
  try { c = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8")); } catch (e) { console.log("bad json:", file); continue; }
  if (!c || !c.slug) continue;
  const f = {};
  for (const k of FIELDS) { const v = c.figures?.[k]; f[k] = typeof v === "number" && Number.isFinite(v) ? v : null; }
  // sanity bounds: never publish an impossible value
  if (f.medianAge != null && (f.medianAge < 20 || f.medianAge > 70)) f.medianAge = null;
  if (f.medianHouseholdIncome2020 != null && (f.medianHouseholdIncome2020 < 30000 || f.medianHouseholdIncome2020 > 250000)) f.medianHouseholdIncome2020 = null;
  if (f.population2021 != null && f.population2021 < 1000) f.population2021 = null;
  if (f.population2021 != null && f.population2016 != null) f.growthPct = Math.round(((f.population2021 - f.population2016) / f.population2016) * 1000) / 10;
  else if (f.growthPct != null && Math.abs(f.growthPct) > 60) f.growthPct = null;
  figures += Object.values(f).filter((v) => v != null).length;
  const figureSources = {};
  for (const [k, u] of Object.entries(c.figureSources || {})) if (isUrl(u) && f[k] != null) figureSources[k] = u;
  const fx = (c.facts || []).filter((x) => x && isUrl(x.url) && x.text && x.publisher).map((x) => ({ text: clean(x.text), url: x.url, publisher: clean(x.publisher) })).slice(0, 3);
  facts += fx.length;
  const allowed = allowedNumbers(f, fx);
  const copy = c.copy || {};
  const before = [...(copy.overview || []), ...Object.values(copy.byService || {})].join(" ");
  const overview = (copy.overview || []).map((p) => scrub(clean(p), allowed)).filter(Boolean);
  const byService = Object.fromEntries(CORE.map((k) => [k, scrub(clean(copy.byService?.[k] || ""), allowed)]).filter(([, v]) => v));
  if ([...overview, ...Object.values(byService)].join(" ").length < before.length - 5) scrubbed++;
  if (overview.length) withCopy++;
  const hasAny = Object.values(f).some((v) => v != null) || fx.length;
  if (!hasAny) { console.log("skip (nothing verified):", c.slug); continue; }
  out[c.slug] = { slug: c.slug, geographyNote: clean(c.geographyNote).slice(0, 120), censusProfileUrl: isUrl(c.censusProfileUrl) && /statcan\.gc\.ca/.test(c.censusProfileUrl) ? c.censusProfileUrl : "", figures: f, figureSources, facts: fx, overview, byService, checkedOn };
}
const body = `// Generated by scripts/gen-city-data.mjs on ${checkedOn}. Do not edit by hand.\n// Figures: Statistics Canada, 2021 Census of Population (municipality). Facts: cited source per item.\nimport type { CityMarketData } from "./city-data";\n\nexport const cityMarketData: Record<string, CityMarketData> = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync("src/lib/city-data.generated.ts", body);
console.log(`wrote ${Object.keys(out).length} cities, ${figures} figures, ${facts} facts, ${withCopy} with copy, ${scrubbed} copies scrubbed of unverified numbers`);
