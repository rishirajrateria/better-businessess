// Builds src/lib/locations-extra.ts from scripts/data/new-places.json (names, coordinates, parent district)
// and the verified research in research/data/cities/<slug>.json (population, descriptor, fact, sectors, areas).
// A place is only published when its research file has a population and a usable descriptor, fact,
// at least 3 sectors and 3 areas. usage: node scripts/gen-extra-cities.mjs
import fs from "node:fs";

const places = JSON.parse(fs.readFileSync("scripts/data/new-places.json", "utf8"));
const ALLOWED = new Set(["Healthcare", "Retail", "Education", "Technology", "Manufacturing", "Tourism", "Construction", "Agriculture", "Government", "Professional services", "Logistics", "Mining", "Finance", "Energy", "Transportation", "Insurance", "Aerospace", "Real estate", "Forestry", "Agri-food", "Food processing", "Automotive", "Life sciences", "Hospitality"]);
const clean = (s) => String(s ?? "").replace(/\s+/g, " ").replace(/—/g, ", ").replace(/–/g, "-").trim().replace(/\.$/, "");
const lowerFirst = (s) => (/^[A-Z][a-z]/.test(s) && !/^(Canada|Ontario|Quebec|Alberta|British|Saskatchewan|Manitoba|Nova|New|Prince|Lake|Greater|Toronto|Montreal|Vancouver|Niagara|Georgian|Ottawa|Halton|York|Durham|Peel|Simcoe|Waterloo|Essex|Fraser|Okanagan|Metro|Highway|Trans)/.test(s) ? s[0].toLowerCase() + s.slice(1) : s);
const fmtPop = (n) => (n >= 1e6 ? `${(Math.round(n / 1e5) / 10).toString()} million` : (Math.round(n / 1000) * 1000).toLocaleString("en-CA"));

const out = [];
const skipped = [];
for (const p of places) {
  const file = `research/data/cities/${p.slug}.json`;
  if (!fs.existsSync(file)) { skipped.push(`${p.slug} (no research yet)`); continue; }
  let r;
  try { r = JSON.parse(fs.readFileSync(file, "utf8")); } catch { skipped.push(`${p.slug} (bad json)`); continue; }
  const m = r.meta || {};
  const pop = r.figures?.population2021 ?? m.populationApprox;
  const descriptor = lowerFirst(clean(m.descriptor));
  const fact = lowerFirst(clean(m.fact));
  const industries = (m.industries || []).filter((x) => ALLOWED.has(x)).slice(0, 6);
  const areas = [...new Set((m.areas || []).map(clean).filter((a) => a && a.toLowerCase() !== p.name.toLowerCase()))].slice(0, 6);
  const problems = [];
  if (!(typeof pop === "number" && pop > 1000)) problems.push("population");
  if (!descriptor || descriptor.length > 100) problems.push("descriptor");
  if (!fact || fact.length > 140) problems.push("fact");
  if (industries.length < 3) problems.push("industries");
  if (areas.length < 3) problems.push("areas");
  if (problems.length) { skipped.push(`${p.slug} (missing ${problems.join(", ")})`); continue; }
  out.push({ slug: p.slug, name: p.name, province: p.province, population: fmtPop(pop), descriptor, industries, areas, fact, lat: p.lat, lng: p.lng, ...(p.parent ? { parent: p.parent } : {}) });
}
const body = `// Generated by scripts/gen-extra-cities.mjs from research/data/cities. Do not edit by hand.\nimport type { City } from "./locations";\n\nexport const extraCities: City[] = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync("src/lib/locations-extra.ts", body);
console.log(`published ${out.length}/${places.length} places`);
if (skipped.length) console.log("skipped:\n  " + skipped.join("\n  "));
